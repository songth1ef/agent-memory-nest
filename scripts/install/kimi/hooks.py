#!/usr/bin/env python3
# -----------------------------------------------------------------------------
# agent-nest hook installer for Kimi Code
#
# Idempotently registers SessionStart / PreToolUse / PostToolUse / Stop hooks
# in ~/.kimi-code/config.toml. Uses comment markers so re-running the installer
# replaces the previous agent-nest block instead of appending duplicates.
#
# Usage:
#   install/kimi/hooks.py <config.toml> <agent_nest_path> <host> <agent_id>
# -----------------------------------------------------------------------------

import os
import re
import shlex
import sys

BEGIN_MARK = "# === agent-nest hooks begin ==="
END_MARK   = "# === agent-nest hooks end ==="
# Block written by the former Nestwork installer; treated as our own.
LEGACY_BEGIN_MARK = "# === " + "nest" + "work hooks begin ==="
LEGACY_END_MARK   = "# === " + "nest" + "work hooks end ==="


AUTO_COMMENT = "# Auto-generated by agent-nest. Do not edit between these marks."
OUR_SCRIPTS = re.compile(r"scripts/hooks/(agent-nest|nest" + "work|hive" + r"queen|session-start)\.sh")


def strip_our_hook_tables(content: str) -> str:
    """Drop [[hooks]] tables that run agent-nest scripts, markers or not.

    Kimi Code may rewrite config.toml and drop comments, so an older install can
    survive without its marker lines; match those tables by their command.
    """
    parts = re.split(r"(?m)^(?=\[)", content)
    kept = [
        part for part in parts
        if not (part.startswith("[[hooks]]") and OUR_SCRIPTS.search(part.replace("\\\\", "/")))
    ]
    text = "".join(kept).replace(AUTO_COMMENT + "\n", "")
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text


def adopt_legacy_block(content: str) -> str:
    return content.replace(LEGACY_BEGIN_MARK, BEGIN_MARK).replace(LEGACY_END_MARK, END_MARK)


def toml_escape(value: str) -> str:
    """Escape a command for a TOML basic (double-quoted) string."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def build_hooks(agent_nest_path: str, host: str, agent_id: str) -> str:
    hook_script   = f"{agent_nest_path}/scripts/hooks/agent-nest.sh"
    session_start = f"{agent_nest_path}/scripts/hooks/session-start.sh"

    start_cmd = "bash " + shlex.join([session_start, host, agent_id])
    pre_cmd  = "bash " + shlex.join([hook_script, "pre", host, agent_id])
    post_cmd = "bash " + shlex.join([hook_script, "post", host, agent_id])
    stop_cmd = "bash " + shlex.join([hook_script, "stop", host, agent_id])

    return f"""{BEGIN_MARK}
# Auto-generated by agent-nest. Do not edit between these marks.

[[hooks]]
event = "SessionStart"
command = "{toml_escape(start_cmd)}"
timeout = 10

[[hooks]]
event = "PreToolUse"
matcher = "Write|Edit"
command = "{toml_escape(pre_cmd)}"
timeout = 10

[[hooks]]
event = "PostToolUse"
matcher = "Write|Edit"
command = "{toml_escape(post_cmd)}"
timeout = 30

[[hooks]]
event = "Stop"
command = "{toml_escape(stop_cmd)}"
timeout = 30

{END_MARK}
"""


def strip_existing_block(content: str) -> str:
    while True:
        begin = content.find(BEGIN_MARK)
        if begin == -1:
            break
        end = content.find(END_MARK, begin)
        if end == -1:
            # Marker begin without end -- strip from begin to EOF (should not happen)
            content = content[:begin]
            break
        # Remove the whole block including surrounding blank lines
        before = content[:begin]
        after = content[end + len(END_MARK):]
        # Collapse multiple trailing/leading blank lines into one
        before = before.rstrip() + "\n"
        after = after.lstrip()
        content = before + ("\n" + after if after else "")
    return content


def main() -> int:
    if len(sys.argv) < 5:
        print("usage: install/kimi/hooks.py <config.toml> <agent_nest_path> <host> <agent_id>", file=sys.stderr)
        return 2

    config_path   = sys.argv[1]
    agent_nest_path = sys.argv[2].replace("\\", "/").rstrip("/")
    host          = sys.argv[3]
    agent_id      = sys.argv[4]

    os.makedirs(os.path.dirname(config_path) or ".", exist_ok=True)

    existing = ""
    if os.path.exists(config_path):
        with open(config_path, encoding="utf-8-sig") as f:
            existing = f.read()

    content = strip_our_hook_tables(strip_existing_block(adopt_legacy_block(existing)))
    block = build_hooks(agent_nest_path, host, agent_id)

    if content and not content.endswith("\n"):
        content += "\n"
    content = content.rstrip() + "\n\n" + block

    with open(config_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"agent-nest hooks registered in {config_path} for {host}/{agent_id}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
